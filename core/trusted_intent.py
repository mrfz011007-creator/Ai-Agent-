from __future__ import annotations

import re
from typing import Any


_FILE_NAME = re.compile(
    r"\bfile\s+([A-Za-z0-9_.-]+(?:/[A-Za-z0-9_.-]+)*\.[A-Za-z0-9]{1,12})",
    re.IGNORECASE,
)
_EXACT_CONTENT = re.compile(
    r"\b(?:isi|konten|content)\b.{0,60}?"
    r"\b(?:persis|tepat|exact(?:ly)?)\b"
    r"(?:.{0,30}?\b(?:berikut|as\s+follows)\b)?"
    r"\s*[:：]\s*(.*)\Z",
    re.IGNORECASE | re.DOTALL,
)


def extract_trusted_file_intent(goal: str) -> dict[str, Any] | None:
    """Extract high-confidence exact file arguments from the original user text.

    Constraints are generated by runtime code, never accepted from model output.
    Ambiguous instructions intentionally return None instead of guessing.
    """
    if not isinstance(goal, str) or not goal.strip():
        return None

    file_matches = list(_FILE_NAME.finditer(goal))
    content_match = _EXACT_CONTENT.search(goal)
    if len(file_matches) != 1 or content_match is None:
        return None

    relative_name = file_matches[0].group(1)
    if relative_name.startswith("/") or any(
        part in {"", ".", ".."} for part in relative_name.split("/")
    ):
        return None

    raw_content = content_match.group(1)
    # A blank line separates the requested content from follow-up instructions.
    content = re.split(r"\r?\n[ \t]*\r?\n", raw_content, maxsplit=1)[0]
    content = content.rstrip("\r\n")

    if not content.strip():
        return None

    return {"nama": relative_name, "isi": content}
